def get_spin_config(state_idx, L):
    """
    Get spin configuration string for a state.
    QuSpin convention: bit=0 → UP (↑), bit=1 → DOWN (↓)
    """
    spins = []
    for i in range(L):
        bit = (state_idx >> i) & 1
        spins.append('↓' if bit else '↑')
    return ''.join(spins)


